public class passorfail {
    public static void main(String args[]) {
        int base = 2;

        switch (base) {
            case 1:
                System.out.println("A");
                break;
            case 2:
                System.out.println("B");
                break;
            case 3:
                System.out.println("C");
                break;
            case 4:
                System.out.println("D");
                break;
            default:
                System.out.println("FAIL");
                break;
        }
    }
}